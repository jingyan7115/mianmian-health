/* Clinical documents are the source of truth. All linked cards are projections. */
(function(root) {
  'use strict';
  const copy = value => JSON.parse(JSON.stringify(value));
  const clean = value => String(value ?? '').trim();
  const validDate = value => { if(!/^\d{4}-\d{2}-\d{2}$/.test(value || '')) return false; const date=new Date(value+'T00:00:00Z');return Number.isFinite(date.getTime()) && date.toISOString().slice(0,10)===value; };
  const statusOptions = ['病历记载', '确诊', '疑似 / 待排', '已排除'];
  function extractDraft(text, report = {}) {
    const rawText = clean(text);
    const normalized = rawText.replace(/([\u3400-\u9fff])[ \t]+(?=[\u3400-\u9fff])/g, '$1');
    const lines = normalized.split(/\n/).map(clean).filter(Boolean);
    const dated = normalized.match(/(?:就诊时间|就诊日期|诊断日期|报告日期)[：:\s]*(20\d{2})[-/.年](\d{1,2})[-/.月](\d{1,2})/);
    const encounterDate = dated ? `${dated[1]}-${dated[2].padStart(2,'0')}-${dated[3].padStart(2,'0')}` : report.recordedAt || '';
    const diagnosisLine = normalized.match(/(?:初步诊断|临床诊断|诊断结果|诊断)[：:]\s*([^\n]+)/);
    const titleCandidate = /(?:初诊|复诊|确诊)$/.test(report.title || '') ? report.title.replace(/(?:初诊|复诊|确诊)$/, '') : '';
    const diagnosis = clean(diagnosisLine?.[1] || titleCandidate).replace(/(?:医嘱|处理|治疗方案)[：:].*$/, '');
    const ordersAt = normalized.search(/医嘱|治疗建议|处理意见|治疗方案|处方|回家后注意/);
    const ordersText = ordersAt >= 0 ? normalized.slice(ordersAt) : normalized;
    const meds = [];
    let route = '';
    for (const line of lines) {
      if (/口服药/.test(line)) route = '口服';
      else if (/外用药|药物治疗.*外用/.test(line)) route = '外用';
      else if (/注意事项|辅助治疗|定期复查/.test(line)) route = '';
      const match = line.replace(/^[门诊记录 ]*[|丨]\s*/, '').match(/^(?:\d+[.、]\s*)?([^：:，,]{2,25})[：:，,]\s*(.+)$/);
      if (!match || !/(?:每次|每天|每日|一日|早晚|小时|q\d+h|bid|sid|tid)/i.test(match[2])) continue;
      if (/清洁|护理|管理|调整|抓挠|复查|事项|疗程|诊断|治疗|时间/.test(match[1])) continue;
      meds.push({id: `ocr-${meds.length + 1}`, name: clean(match[1]), dose: match[2].match(/每次\s*([^，。,；;]+)/)?.[1] || '', frequency: match[2].match(/(?:每天|每日|一日)[^，。,；;]+|早晚各?[^，。,；;]+|\d+小时[^，。,；;]+/g)?.join('；') || '', route, startDate:'', endDate:'', cycle:'', notes:line, status:'医嘱已记录 · 执行待核对', relatedEntryId:''});
    }
    return {schemaVersion:1, reviewStatus:'draft', encounterDate, diagnosisDate:'', diagnosis, diagnosisStatus: /疑似|考虑|待排|可能/.test(diagnosis) ? '疑似 / 待排' : /排除|未见/.test(diagnosis) ? '已排除' : '病历记载', rawText, ordersText,
      careText:lines.filter(x=>/皮肤清洁|环境管理|避免抓挠|日常护理/.test(x)).join('\n'),
      nutritionText:lines.filter(x=>/饮食调整|饮食建议|营养支持/.test(x)).join('\n'),
      monitoringText:lines.filter(x=>/监测|观察|注意事项/.test(x)).join('\n'),
      followUpText:lines.filter(x=>/复诊|复查|随访/.test(x)).join('\n'), followUpDate:'', precautions:'', relatedEntryIds:[], meds};
  }
  function validate(clinical) {
    if (!clinical.diagnosis && !clinical.ordersText && !(clinical.meds || []).length && !clinical.careText && !clinical.nutritionText && !clinical.followUpText) throw Error('请至少填写诊断、医嘱、用药或护理内容；无需数字指标。');
    if (!validDate(clinical.encounterDate)) throw Error('请填写有效的就诊日期。');
    for (const date of [clinical.diagnosisDate, clinical.followUpDate]) if (date && !validDate(date)) throw Error('请核对诊断或复诊日期。');
    if (clinical.diagnosisStatus === '确诊' && !clinical.diagnosisDate) throw Error('确诊记录需要原报告明确的确诊日期；不明确时请选择“病历记载”。');
    const ids = new Set();
    for (const med of clinical.meds || []) {
      if (!clean(med.name)) throw Error('请填写每条用药的名称；原文未注明时可以写“未注明药名的外用药液”。');
      if (!med.id || ids.has(med.id)) throw Error('用药记录编号重复，请删除重复行再新增。');
      ids.add(med.id);
      for (const date of [med.startDate,med.endDate]) if (date && !validDate(date)) throw Error('请核对用药日期。');
      if (med.startDate && med.endDate && med.endDate < med.startDate) throw Error('用药结束日期不能早于开始日期。');
    }
    return clinical;
  }
  function summary(c) { return [c.diagnosis && `${c.diagnosis}（${c.diagnosisStatus}）`, c.meds?.length && `${c.meds.length} 条用药医嘱`, c.careText && '日常护理', c.nutritionText && '饮食医嘱', c.followUpText && '复诊要求'].filter(Boolean).join(' · ') || '医嘱已核对'; }
  function synchronize(source) {
    const next = copy(source);
    const originals = next.moduleEntries || [];
    // Only entries generated by this feature are replaced; manual records remain untouched.
    next.moduleEntries = originals.filter(x => x.sourceKind !== 'clinical-report');
    for (const report of next.labReports || []) {
      const c = report.clinical;
      if (!c || c.reviewStatus !== 'confirmed') continue;
      const add = (suffix, module, title, detail, data, recordedAt) => {
        const id = `clinical-${report.id}-${suffix}`;
        const old = originals.find(x => x.id === id);
        if (old?.data?.reminderCompletedAt && old.data.endDate === data.endDate) data.reminderCompletedAt = old.data.reminderCompletedAt;
        next.moduleEntries.push({id,module,recordedAt:recordedAt || c.encounterDate || report.recordedAt,title,summary:detail,data,
          sourceKind:'clinical-report',sourceReportId:report.id,sourceKey:`clinical:${report.id}:${suffix}`,imageUrls:[],
          createdAt:old?.createdAt || c.reviewedAt || report.createdAt,updatedAt:c.reviewedAt || report.updatedAt});
      };
      if (c.diagnosis) add('diagnosis','diagnosis',c.diagnosis,summary(c),{status:c.diagnosisStatus,diagnosisDate:c.diagnosisDate || '原文未明确',encounterDate:c.encounterDate,ordersText:c.ordersText,precautions:c.precautions},c.diagnosisDate);
      if (c.careText || c.nutritionText || c.monitoringText || c.followUpText || c.precautions || (!c.meds?.length && c.ordersText)) {
        add('care','instructions',`${c.diagnosis || report.title} · 照护医嘱`,c.followUpText || c.careText || c.ordersText,{careText:c.careText,nutritionText:c.nutritionText,monitoringText:c.monitoringText,followUpText:c.followUpText,precautions:c.precautions,ordersText:c.ordersText,
          endDate:c.followUpDate,reminderAction:'复诊 / 复查',reminderNote:c.followUpText});
      }
      for (const med of c.meds || []) add(`med-${med.id}`,'treatment',med.name,med.notes || '来自已核对的就诊医嘱',{
        treatmentClass:med.route || '原文未明确',indication:c.diagnosis,dose:med.dose || '原文未明确',frequency:med.frequency || '原文未明确',route:med.route,
        startDate:med.startDate || '未确认实际开始日期',endDate:med.endDate,cycle:med.cycle || '原文未明确',status:med.status || '医嘱已记录 · 执行待核对',notes:med.notes,
        reminderAction:'联系医生核对后续用药',reminderNote:'医嘱到期提醒不代表可以自行停药。'},med.startDate);
      report.documentType = report.results?.length ? 'mixed' : 'clinical';
      report.summary = summary(c);
      report.panels = ['诊断与医嘱', ...(report.results?.length ? ['检验指标'] : [])];
      for (const metric of next.metrics || []) if (metric.sourceReportId === report.id || (report.reportPages || []).some(p=>p.imageUrl && p.imageUrl === metric.sourceUploadId)) { metric.sourceReportId=report.id;metric.recordedAt=c.encounterDate; }
      for (const upload of next.uploads || []) if ((report.reportPages || []).some(p=>p.imageUrl === upload.url)) {upload.recordedAt=c.encounterDate;upload.title=report.title;}
      for (const rec of next.records || []) if (rec.sourceReportId === report.id || (report.reportPages || []).some(p=>p.imageUrl && p.imageUrl === rec.sourceUploadId)) {
        rec.sourceReportId = report.id; rec.summary = report.summary; rec.category = '诊断与医嘱'; rec.recordedAt = c.encounterDate;
      }
    }
    return next;
  }
  function confirmReport(source, reportId, clinical, timestamp = new Date().toISOString()) {
    validate(clinical);
    const next = copy(source), report = next.labReports.find(x => x.id === reportId);
    if (!report) throw Error('原报告已不存在，请刷新后重试。');
    const before = report.clinical;
    if (before?.reviewStatus === 'confirmed') report.clinicalHistory = [...(report.clinicalHistory || []), before];
    report.clinical = {...copy(clinical),reviewStatus:'confirmed',reviewedAt:timestamp,schemaVersion:1};
    report.recordedAt = clinical.encounterDate; report.updatedAt=timestamp;
    return synchronize(next);
  }
  const api = {extractDraft,validate,summary,synchronize,confirmReport,statusOptions,validDate};
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.ClinicalReports = api;
})(typeof window !== 'undefined' ? window : globalThis);
